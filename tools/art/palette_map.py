"""Maps every color literal in the approved v2 mockups onto palette.V2.

Usage (from the repo root):
    py tools/art/palette_map.py            # rewrite docs/art-direction/v2/palette-map.md
    py tools/art/palette_map.py --check    # exit 1 if the committed report is stale

Each mockup color is one of:
- exact:    the hex is a v2 palette color;
- snapped:  within SNAP_DISTANCE (RGB Euclidean) of a v2 color, which it maps to
            (the mockups were drawn freehand, so near-duplicates are common);
- deferred: further away, so it belongs to a later task's ramps. The task is
            inferred from where the color is used (biome studies -> AR-6,
            enemies -> AR-8, portraits -> AR-9).
Not registered in build_all.py: this is a report, not an asset.
"""

from __future__ import annotations

import math
import re
import sys
from collections import defaultdict
from pathlib import Path

ART_DIR = Path(__file__).resolve().parent
REPO_ROOT = ART_DIR.parents[1]
if str(ART_DIR) not in sys.path:
    sys.path.insert(0, str(ART_DIR))

import palette  # noqa: E402

MOCKUP_DIR = REPO_ROOT / "docs" / "art-direction" / "v2" / "mockup-src"
REPORT = REPO_ROOT / "docs" / "art-direction" / "v2" / "palette-map.md"
SNAP_DISTANCE = 20.0
HEX = re.compile(r"#[0-9A-Fa-f]{6}\b")

# Recipes whose colors are scheduled for a later task, matched against the
# line a color appears on. First match wins.
DEFERRED_RULES: tuple[tuple[str, str], ...] = (
    ("GOB=", "AR-8 enemies (Dynamite Goblin)"),
    ("BAT2=", "AR-8 enemies (Cave Bat)"),
    ("const SP=", "AR-8/AR-11 v1 mockup icons and enemies"),
    ("hydra:{", "AR-11 relic and ability icons"),
    ("clock:{", "AR-11 relic and ability icons"),
    ("boots:{", "AR-11 relic and ability icons"),
    ("gold:{", "AR-11 relic and ability icons"),
    ("fire:{", "AR-11 relic and ability icons"),
    ("runes=", "AR-4 shrine props"),
    ("Math.abs(i-j)<=1", "AR-4 shrine props (rug)"),
    ("crystal2(", "AR-6 other biomes (crystal)"),
    ("mush2(", "AR-6 other biomes (fungal)"),
    ("globalCompositeOperation", "AR-17 lighting grade (not a sprite color)"),
    ("PORT", "AR-9 portraits"),
    ("PPAL", "AR-9 portraits"),
)


def _dist(a: str, b: str) -> float:
    ra, rb = palette.rgb(a), palette.rgb(b)
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(ra, rb, strict=True)))


def _v2_by_hex() -> dict[str, str]:
    out: dict[str, str] = {}
    for name, value in {**palette.V2, **palette.ACCENT}.items():
        out.setdefault(value, name)
    return out


def collect() -> dict[str, dict[str, object]]:
    """hex -> {count, files, lines} for every literal in the mockup source."""
    usage: dict[str, dict[str, object]] = defaultdict(lambda: {"count": 0, "files": set(), "lines": []})
    for path in sorted(MOCKUP_DIR.iterdir()):
        if path.suffix not in (".js", ".html"):
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            for m in HEX.finditer(line):
                h = m.group().upper()
                u = usage[h]
                u["count"] = int(u["count"]) + 1
                u["files"].add(path.name)  # type: ignore[union-attr]
                u["lines"].append(line)  # type: ignore[union-attr]
    return dict(usage)


def classify() -> list[dict[str, object]]:
    by_hex = _v2_by_hex()
    rows: list[dict[str, object]] = []
    for h, u in sorted(collect().items()):
        if h in by_hex:
            rows.append({"hex": h, "kind": "exact", "name": by_hex[h], "dist": 0.0, **u})
            continue
        name, value = min(palette.V2.items(), key=lambda kv: (_dist(h, kv[1]), kv[0]))
        d = _dist(h, value)
        if d <= SNAP_DISTANCE:
            rows.append({"hex": h, "kind": "snapped", "name": name, "dist": d, **u})
            continue
        files: set[str] = u["files"]  # type: ignore[assignment]
        task = "AR-6 other biomes" if files == {"Biomes.part.html"} else ""
        if not task:
            for needle, label in DEFERRED_RULES:
                if any(needle in line for line in u["lines"]):  # type: ignore[union-attr]
                    task = label
                    break
        rows.append({"hex": h, "kind": "deferred", "name": name, "dist": d, "task": task or "unassigned", **u})
    return rows


def render(rows: list[dict[str, object]]) -> str:
    counts = defaultdict(int)
    for r in rows:
        counts[r["kind"]] += 1
    unassigned = [r for r in rows if r.get("task") == "unassigned"]
    lines = [
        "# v2 palette map",
        "",
        "Generated by `py tools/art/palette_map.py`; do not edit by hand. Every color literal in",
        "`docs/art-direction/v2/mockup-src/` mapped onto `palette.V2` (SPEC-art-audio, \"Art direction v2\", D5).",
        "",
        f"- Exact: {counts['exact']}",
        f"- Snapped (within {SNAP_DISTANCE:g} RGB of a v2 color, which it maps to): {counts['snapped']}",
        f"- Deferred to a later task's ramps: {counts['deferred']} ({len(unassigned)} unassigned)",
        "",
        "| Mockup color | Kind | v2 name | Distance | Uses | Files | Deferred to |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        files = ", ".join(sorted(r["files"]))  # type: ignore[arg-type]
        lines.append(f"| `{r['hex']}` | {r['kind']} | `{r['name']}` | {r['dist']:.1f} | {r['count']} | {files} | {r.get('task', '')} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render(classify())
    if "--check" in argv:
        current = REPORT.read_text(encoding="utf-8") if REPORT.exists() else ""
        if current != text:
            print(f"{REPORT} is stale: run py tools/art/palette_map.py")
            return 1
        return 0
    REPORT.write_text(text, encoding="utf-8")
    print(text.split("| Mockup color")[0])
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
